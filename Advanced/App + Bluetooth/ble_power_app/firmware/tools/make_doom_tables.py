#!/usr/bin/env python3
"""Generates doom_tables.h: sine / reciprocal / per-column ray tables for the raycaster.

Angles are 0..1023 for a full turn. Run:  python3 make_doom_tables.py > ../doom_tables.h
"""
import math

FOV_DEG = 66        # horizontal field of view
COLS = 64           # rays per frame (each drawn 2 pixels wide)

q = [round(16384 * math.sin(math.pi / 2 * i / 256)) for i in range(257)]           # Q14
inv = []
for i in range(257):
    s = math.sin(math.pi / 2 * i / 256)
    inv.append(65535 if s < 1 / 255 else min(65535, round(256 / s)))                 # Q8.8

half = math.radians(FOV_DEG / 2)
offs, coss = [], []
for c in range(COLS):
    x = (c + 0.5 - COLS / 2) / (COLS / 2)            # -1 .. +1 across the screen
    a = math.atan(x * math.tan(half))
    offs.append(round(a * 1024 / (2 * math.pi)))
    coss.append(round(32767 * math.cos(a)))

d_px = 64 / math.tan(half)                         # projection distance in screen pixels

def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] PROGMEM = {{"]
    for k in range(0, len(vals), per):
        out.append("\t" + ", ".join(str(v) for v in vals[k:k + per]) + ",")
    out.append("};")
    return "\n".join(out)

print("/* doom_tables.h - generated by tools/make_doom_tables.py, do not edit */")
print("#ifndef DOOM_TABLES_H_\n#define DOOM_TABLES_H_\n")
print("#include <stdint.h>\n#include \"pgm_compat.h\"\n")
print(f"#define DOOM_FOV_DEG {FOV_DEG}")
print(f"#define DOOM_COLS    {COLS}")
print(f"#define DOOM_DPX     {d_px:.1f}f  /* projection distance, screen pixels */\n")
print("/* sin over a quarter turn, Q14 (16384 = 1.0) */")
print(arr("sin_q", "int16_t", q))
print("\n/* 1/|sin| over a quarter turn, Q8.8, saturated at 65535 */")
print(arr("inv_q", "uint16_t", inv))
print("\n/* ray angle offset of each column from the view direction (1024 = full turn) */")
print(arr("col_off", "int16_t", offs, 16))
print("\n/* cos of that offset, Q15: removes the fish-eye effect */")
print(arr("col_cos", "uint16_t", coss, 12))
low = [(1 << n) - 1 for n in range(33)]
print("\n/* lowmask[n] = rows 0..n-1 set: spans without slow variable shifts on the AVR */")
print(arr("lowmask", "uint32_t", [f"0x{v:08X}UL" for v in low], 6))

GUN = [  # 16 px wide, drawn in rows 22..31
    "......####......",
    ".....#....#.....",
    ".....#....#.....",
    "....########....",
    "...##......##...",
    "..############..",
    "..#..........#..",
    ".##..........##.",
    ".#............#.",
    "################",
]
cols = []
for x in range(16):
    m = 0
    for r, row in enumerate(GUN):
        if row[x] == "#":
            m |= 1 << (22 + r)
    cols.append(f"0x{m:08X}UL")
print("\n/* gun, one row mask per screen column 56..71 */")
print(arr("gun_cols", "uint32_t", cols, 4))
print("\n#endif /* DOOM_TABLES_H_ */")
