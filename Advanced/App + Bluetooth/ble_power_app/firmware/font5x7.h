/* One column (0-4) of a character; 0 for the gap column (5) or unknown chars. */
static inline uint8_t font_col(char c, uint8_t col)
{
	if (col > 4) return 0;
	if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
	if (c >= '0' && c <= '9') return pgm_read_byte(&font_digit[c - '0'][col]);
	if (c >= 'A' && c <= 'Z') return pgm_read_byte(&font_alpha[c - 'A'][col]);
	switch (c) {
		case '-': return pgm_read_byte(&font_punct[1][col]);
		case '.': return pgm_read_byte(&font_punct[2][col]);
		case '/': return pgm_read_byte(&font_punct[3][col]);
		case ':': return pgm_read_byte(&font_punct[4][col]);
		default:  return 0;
	}
}

/* Column x (in pixels) of a text string drawn from x = 0, 6 pixels per character. */
static inline uint8_t font_text_col(const char *s, uint8_t len, uint8_t x)
{
	uint8_t i = x / 6;
	if (i >= len) return 0;
	return font_col(s[i], x % 6);
}

